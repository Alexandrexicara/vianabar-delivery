BEGIN;

-- Garante IDs automáticos nas tabelas usadas pelos pedidos e webhooks.
-- A versão anterior do esquema deixava essas colunas BIGINT NOT NULL sem DEFAULT,
-- fazendo o INSERT falhar porque a aplicação não envia IDs manuais.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='cardapio_order_items'
      AND column_name='id' AND is_identity='NO' AND column_default IS NULL
  ) THEN
    ALTER TABLE public.cardapio_order_items
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='woovi_webhook_events'
      AND column_name='id' AND is_identity='NO' AND column_default IS NULL
  ) THEN
    ALTER TABLE public.woovi_webhook_events
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='woovi_commission_transfers'
      AND column_name='id' AND is_identity='NO' AND column_default IS NULL
  ) THEN
    ALTER TABLE public.woovi_commission_transfers
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

SELECT setval(pg_get_serial_sequence('public.cardapio_order_items','id'),
              GREATEST(COALESCE((SELECT MAX(id) FROM public.cardapio_order_items),0)+1,1), false);
SELECT setval(pg_get_serial_sequence('public.woovi_webhook_events','id'),
              GREATEST(COALESCE((SELECT MAX(id) FROM public.woovi_webhook_events),0)+1,1), false);
SELECT setval(pg_get_serial_sequence('public.woovi_commission_transfers','id'),
              GREATEST(COALESCE((SELECT MAX(id) FROM public.woovi_commission_transfers),0)+1,1), false);

COMMIT;
