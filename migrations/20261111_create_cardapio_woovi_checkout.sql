BEGIN;

CREATE TABLE IF NOT EXISTS cardapio_orders (
  id VARCHAR(80) PRIMARY KEY,
  store_id VARCHAR(120) NOT NULL,
  customer_name VARCHAR(160) NOT NULL,
  customer_phone VARCHAR(40),
  table_number VARCHAR(40),
  observations TEXT,
  subtotal_cents BIGINT NOT NULL CHECK (subtotal_cents >= 0),
  total_cents BIGINT NOT NULL CHECK (total_cents > 0),
  currency CHAR(3) NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
  status VARCHAR(24) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','preparing','ready','delivered','completed','cancelled')),
  payment_method VARCHAR(16) NOT NULL CHECK (payment_method IN ('pix','cash','card')),
  payment_status VARCHAR(32) NOT NULL DEFAULT 'pending'
    CHECK (payment_status IN ('pending','paid','awaiting_in_person','failed','expired','refunded','needs_review')),
  provider VARCHAR(32),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_cardapio_orders_store_created
  ON cardapio_orders (store_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cardapio_orders_store_status
  ON cardapio_orders (store_id, status, payment_status);

CREATE TABLE IF NOT EXISTS cardapio_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id VARCHAR(80) NOT NULL REFERENCES cardapio_orders(id) ON DELETE CASCADE,
  product_id TEXT NOT NULL,
  product_name VARCHAR(200) NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents >= 0),
  total_cents BIGINT NOT NULL CHECK (total_cents >= 0),
  sector VARCHAR(40) NOT NULL DEFAULT 'kitchen',
  notes TEXT
);
CREATE INDEX IF NOT EXISTS idx_cardapio_order_items_order ON cardapio_order_items(order_id);

CREATE TABLE IF NOT EXISTS merchant_woovi_accounts (
  store_id VARCHAR(120) PRIMARY KEY,
  app_id_ciphertext BYTEA NOT NULL,
  app_id_iv BYTEA NOT NULL,
  app_id_tag BYTEA NOT NULL,
  webhook_token_hash CHAR(64) NOT NULL,
  webhook_registered BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(24) NOT NULL DEFAULT 'pending_webhook'
    CHECK (status IN ('pending_webhook','active','suspended','error')),
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cardapio_payment_transactions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id VARCHAR(80) NOT NULL UNIQUE REFERENCES cardapio_orders(id) ON DELETE RESTRICT,
  store_id VARCHAR(120) NOT NULL,
  provider VARCHAR(32) NOT NULL,
  correlation_id VARCHAR(160) NOT NULL UNIQUE,
  provider_charge_id VARCHAR(200),
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  currency CHAR(3) NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
  status VARCHAR(24) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','active','paid','expired','failed','refunded','needs_review')),
  br_code TEXT,
  qr_code_image TEXT,
  payment_link_url TEXT,
  provider_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  commission_amount_cents BIGINT NOT NULL DEFAULT 0 CHECK (commission_amount_cents >= 0),
  commission_status VARCHAR(24) NOT NULL DEFAULT 'pending'
    CHECK (commission_status IN ('pending','processing','paid','failed','needs_review','not_applicable')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_cardapio_payments_store_created
  ON cardapio_payment_transactions(store_id, created_at DESC);

CREATE TABLE IF NOT EXISTS woovi_webhook_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key VARCHAR(220) NOT NULL UNIQUE,
  correlation_id VARCHAR(160) NOT NULL,
  event_type VARCHAR(100) NOT NULL,
  payload JSONB NOT NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS woovi_commission_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id VARCHAR(80) NOT NULL UNIQUE REFERENCES cardapio_orders(id) ON DELETE RESTRICT,
  correlation_id VARCHAR(180) NOT NULL UNIQUE,
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  status VARCHAR(24) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','processing','paid','failed','needs_review')),
  provider_reference VARCHAR(200),
  failure_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  paid_at TIMESTAMPTZ
);

COMMIT;
