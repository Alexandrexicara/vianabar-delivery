-- Controle de valores de entrega de motoboys contratados pelo comerciante.
-- Este fluxo e separado do split automatico do pedido.
-- Valores sempre em centavos (BRL); nao existe calculo percentual neste modelo.
-- A custodia/reserva financeira nao e definida nesta migration: sera decidida separadamente.

BEGIN;

CREATE TABLE IF NOT EXISTS merchant_delivery_obligations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id VARCHAR(160) NOT NULL,
  motoboy_id VARCHAR(160) NOT NULL,
  order_id VARCHAR(160) NOT NULL,
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  currency CHAR(3) NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
  earned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  due_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'due', 'in_batch', 'paid', 'cancelled')),
  payout_batch_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_delivery_obligation_order_motoboy
    UNIQUE (merchant_id, order_id, motoboy_id)
);

CREATE INDEX IF NOT EXISTS idx_delivery_obligations_merchant_due
  ON merchant_delivery_obligations (merchant_id, due_at, status);

CREATE INDEX IF NOT EXISTS idx_delivery_obligations_motoboy
  ON merchant_delivery_obligations (motoboy_id, status, due_at);

CREATE TABLE IF NOT EXISTS merchant_delivery_payout_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id VARCHAR(160) NOT NULL,
  total_cents BIGINT NOT NULL CHECK (total_cents > 0),
  currency CHAR(3) NOT NULL DEFAULT 'BRL' CHECK (currency = 'BRL'),
  period_start TIMESTAMPTZ NOT NULL,
  period_end TIMESTAMPTZ NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'pending_authorization'
    CHECK (status IN ('pending_authorization', 'authorized', 'processing', 'paid', 'failed', 'cancelled')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  authorized_at TIMESTAMPTZ,
  authorized_by VARCHAR(160),
  processed_at TIMESTAMPTZ,
  provider VARCHAR(80),
  provider_reference VARCHAR(200),
  failure_reason TEXT,
  idempotency_key VARCHAR(160) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (period_end >= period_start),
  CHECK (
    status NOT IN ('authorized', 'processing', 'paid')
    OR (authorized_at IS NOT NULL AND authorized_by IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_delivery_payout_batches_merchant
  ON merchant_delivery_payout_batches (merchant_id, status, requested_at DESC);

DO $
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_delivery_obligation_batch'
  ) THEN
    ALTER TABLE merchant_delivery_obligations
      ADD CONSTRAINT fk_delivery_obligation_batch
      FOREIGN KEY (payout_batch_id)
      REFERENCES merchant_delivery_payout_batches(id)
      ON DELETE RESTRICT;
  END IF;
END $;

CREATE TABLE IF NOT EXISTS merchant_delivery_payout_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES merchant_delivery_payout_batches(id) ON DELETE RESTRICT,
  obligation_id BIGINT NOT NULL REFERENCES merchant_delivery_obligations(id) ON DELETE RESTRICT,
  amount_cents BIGINT NOT NULL CHECK (amount_cents > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_delivery_payout_item_obligation UNIQUE (obligation_id)
);

CREATE TABLE IF NOT EXISTS merchant_delivery_payout_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES merchant_delivery_payout_batches(id) ON DELETE RESTRICT,
  event_type VARCHAR(48) NOT NULL,
  actor_id VARCHAR(160),
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_delivery_payout_events_batch
  ON merchant_delivery_payout_events (batch_id, created_at);

COMMIT;
