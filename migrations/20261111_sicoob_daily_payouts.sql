BEGIN;
CREATE TABLE IF NOT EXISTS sicoob_merchant_connections (
 merchant_id VARCHAR(160) PRIMARY KEY,
 status VARCHAR(24) NOT NULL DEFAULT 'not_configured' CHECK (status IN ('not_configured','pending_approval','active','suspended','error')),
 client_id TEXT, client_secret_ciphertext BYTEA, certificate_ciphertext BYTEA, private_key_ciphertext BYTEA,
 pix_receivements_enabled BOOLEAN NOT NULL DEFAULT FALSE, pix_payments_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 provider_account_reference TEXT, approved_at TIMESTAMPTZ, last_error TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK (status <> 'active' OR (client_id IS NOT NULL AND client_secret_ciphertext IS NOT NULL AND certificate_ciphertext IS NOT NULL AND private_key_ciphertext IS NOT NULL AND pix_receivements_enabled AND pix_payments_enabled))
);
CREATE TABLE IF NOT EXISTS delivery_pix_recipients (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_type VARCHAR(20) NOT NULL CHECK (owner_type IN ('platform','motoboy')),
 owner_id VARCHAR(160) NOT NULL, pix_key_ciphertext BYTEA NOT NULL, pix_key_fingerprint CHAR(64) NOT NULL,
 pix_key_type VARCHAR(20) NOT NULL CHECK (pix_key_type IN ('cpf','cnpj','email','phone','evp')),
 holder_name VARCHAR(160), status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active','pending_validation','disabled')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(owner_type, owner_id)
);
CREATE TABLE IF NOT EXISTS sicoob_delivery_obligations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, merchant_id VARCHAR(160) NOT NULL,
 motoboy_id VARCHAR(160) NOT NULL, order_id VARCHAR(160) NOT NULL,
 amount_cents BIGINT NOT NULL CHECK (amount_cents > 0), earned_at TIMESTAMPTZ NOT NULL, due_at TIMESTAMPTZ NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','due','in_batch','paid','cancelled')),
 payout_batch_id BIGINT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(merchant_id, order_id, motoboy_id), CHECK (due_at >= earned_at)
);
CREATE INDEX IF NOT EXISTS idx_sicoob_obligations_due ON sicoob_delivery_obligations(merchant_id,due_at,status,motoboy_id);
CREATE TABLE IF NOT EXISTS sicoob_daily_payout_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, merchant_id VARCHAR(160) NOT NULL, motoboy_id VARCHAR(160) NOT NULL,
 total_cents BIGINT NOT NULL CHECK (total_cents > 0), period_start TIMESTAMPTZ NOT NULL, period_end TIMESTAMPTZ NOT NULL,
 idempotency_key VARCHAR(200) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','paid','failed','needs_review')),
 provider_reference VARCHAR(200), failure_reason TEXT, attempted_at TIMESTAMPTZ, processed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), CHECK (period_end >= period_start)
);
CREATE INDEX IF NOT EXISTS idx_sicoob_batches_pending ON sicoob_daily_payout_batches(status,created_at) WHERE status IN ('pending','failed','needs_review');
CREATE TABLE IF NOT EXISTS sicoob_daily_payout_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL REFERENCES sicoob_daily_payout_batches(id) ON DELETE RESTRICT,
 obligation_id BIGINT NOT NULL REFERENCES sicoob_delivery_obligations(id) ON DELETE RESTRICT,
 amount_cents BIGINT NOT NULL CHECK (amount_cents > 0), UNIQUE(batch_id,obligation_id), UNIQUE(obligation_id)
);
ALTER TABLE sicoob_delivery_obligations DROP CONSTRAINT IF EXISTS sicoob_delivery_obligations_payout_batch_id_fkey;
ALTER TABLE sicoob_delivery_obligations ADD CONSTRAINT sicoob_delivery_obligations_payout_batch_id_fkey FOREIGN KEY (payout_batch_id) REFERENCES sicoob_daily_payout_batches(id) ON DELETE RESTRICT;
CREATE TABLE IF NOT EXISTS sicoob_payout_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL REFERENCES sicoob_daily_payout_batches(id) ON DELETE RESTRICT,
 event_type VARCHAR(48) NOT NULL, details JSONB NOT NULL DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_sicoob_payout_events_batch ON sicoob_payout_events(batch_id,created_at);
COMMIT;
